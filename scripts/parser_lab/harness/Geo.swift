func runGeo() {
    for c in geoCases {
        let r = BillParser.parse(lines: c.lines)
        var okAmount = abs(r.amount - c.amount) < 0.005
        var why = ""
        if !okAmount { why += " 金额得 \(r.amount)" }
        if let t = c.tier, r.amountTier != t { okAmount = false; why += " 档位得 \(r.amountTier.rawValue)" }
        if let t = c.type, r.type != t { okAmount = false; why += " 收支得 \(r.type.rawValue)" }
        if let z = c.zero, r.zeroPaid != z { okAmount = false; why += " zeroPaid=\(r.zeroPaid)" }
        ok(okAmount, "GEO \(c.name)\(why)")
    }
}
