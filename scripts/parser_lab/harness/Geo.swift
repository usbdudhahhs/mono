// 几何路径用例：parse(text:) 里所有行高度、横坐标都是假的（height 0.02 / width 1），
// 字号、左右、上下这些真正决定金额归属的逻辑在文本路径下几乎不参与。
// 这一组用真实 Vision 坐标（原点左下）把几何分支逐条打进去。

struct GeoCase {
    let name: String
    let lines: [OCRLine]
    let amount: Double
    let tier: AmountTier?
    let type: RecordType?
    let zero: Bool?
    let alts: [Double]?
}

/// topY 是从页面顶端量的距离，内部换算成 Vision 的左下原点坐标
func R(_ t: String, _ h: CGFloat, _ topY: CGFloat, _ x: CGFloat = 0.12, _ w: CGFloat = 0.72, _ c: Float = 0.94) -> OCRLine {
    OCRLine(text: t, confidence: c, height: h,
            box: CGRect(x: x, y: 1 - topY - h, width: w, height: h))
}

