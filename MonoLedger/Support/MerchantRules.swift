        ("claim",  ["报销", "差旅报销"]),
        ("giftIn", ["礼金", "收到转账", "转入"])
    ]

    /// 在文本中找分类，长词优先
    static func match(_ text: String, type: RecordType = .expense) -> Hit? {
        guard !text.isEmpty else { return nil }
        let lowered = text.lowercased()
        let source = type == .income ? incomeTable : table
        var best: Hit?

        for (categoryID, keywords) in source {
            for keyword in keywords {
                guard lowered.contains(keyword.lowercased()) else { continue }
                let score = keyword.count
                if best == nil || score > (best?.score ?? 0) {
                    best = Hit(categoryID: categoryID, keyword: keyword, score: score)
                }
            }
        }
        return best
    }
